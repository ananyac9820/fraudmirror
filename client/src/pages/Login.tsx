import { useState, type FormEvent } from 'react';
import { Navigate } from 'react-router-dom';
import { useAppDispatch, useAppSelector } from '../store';
import { login } from '../store/authSlice';
import Mountains from '../components/Mountains';
import { Container, Footer, Wordmark } from '../components/ui';
import { DEMO_MODE } from '../lib/api';

const DEMO = [
  { email: 'analyst@fraudmirror.dev', role: 'Analyst', desc: 'Reviews and resolves alerts' },
  { email: 'redteam@fraudmirror.dev', role: 'Red team', desc: 'Launches simulated attacks' },
  { email: 'admin@fraudmirror.dev', role: 'Admin', desc: 'Full access' },
];

export default function Login() {
  const dispatch = useAppDispatch();
  const { token, status, error } = useAppSelector((s) => s.auth);
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');

  if (token) return <Navigate to="/dashboard" replace />;

  const submit = (e: FormEvent) => {
    e.preventDefault();
    dispatch(login({ email, password }));
  };

  return (
    <div className="flex min-h-screen flex-col">
      <header className="border-b border-line">
        <Container className="flex h-16 items-center justify-between">
          <Wordmark />
          <span className="text-[11px] uppercase tracking-[0.16em] text-muted">Synthetic data</span>
        </Container>
      </header>

      <div className="relative overflow-hidden">
        <Mountains className="absolute inset-x-0 bottom-0 h-[70%] w-full" />
        <Container className="relative pb-40 pt-16 sm:pb-56 sm:pt-24">
          <p className="eyebrow">A payment fraud laboratory</p>
          <h1 className="mt-6 text-[64px] font-light leading-[0.9] tracking-tight sm:text-[112px] lg:text-[136px]">
            <span className="display">Fraud</span>
            <span className="block pl-[12%]">Mirror</span>
          </h1>
        </Container>
      </div>

      <Container className="grid gap-14 py-14 lg:grid-cols-2 lg:gap-24">
        <div className="max-w-[46ch]">
          <p className="text-[17px] leading-relaxed text-ink">
            Watch synthetic payments stream in, see which ones the detector flags and why, review the cases, then switch sides and study what slipped
            through.
          </p>
          <p className="mt-5 text-[14px] leading-relaxed text-muted">
            Every transaction, account and attack on this platform is generated by its own simulator. No real card, bank or personal data is used.
            {DEMO_MODE && ' This public copy runs entirely in your browser.'}
          </p>
        </div>

        <div>
          <form onSubmit={submit} className="flex flex-col gap-6">
            <h2 className="eyebrow">Sign in</h2>
            <label className="block text-[12px] text-muted">
              Email
              <input value={email} onChange={(e) => setEmail(e.target.value)} type="email" required className="field mt-1" placeholder="you@fraudmirror.dev" />
            </label>
            <label className="block text-[12px] text-muted">
              Password
              <input value={password} onChange={(e) => setPassword(e.target.value)} type="password" required className="field mt-1" />
            </label>
            {error && <p className="text-[13px] text-signal">{error}</p>}
            <div>
              <button disabled={status === 'loading'} className="btn btn-primary">
                {status === 'loading' ? 'Signing in' : 'Sign in'}
              </button>
            </div>
          </form>

          <div className="mt-12">
            <h2 className="eyebrow">Demo accounts, password demo123</h2>
            <ul className="mt-3 border-t border-line">
              {DEMO.map((d) => (
                <li key={d.email} className="flex items-center justify-between gap-4 border-b border-line py-3">
                  <div className="min-w-0">
                    <div className="text-[14px] text-ink">{d.role}</div>
                    <div className="truncate font-mono text-[12px] text-muted">{d.email}</div>
                  </div>
                  <button
                    type="button"
                    onClick={() => {
                      setEmail(d.email);
                      setPassword('demo123');
                    }}
                    className="link shrink-0 text-[13px]"
                  >
                    Use account
                  </button>
                </li>
              ))}
            </ul>
          </div>
        </div>
      </Container>
      <div className="flex-1" />
      <Footer />
    </div>
  );
}
